package com.unisence.iot.rule.sdk;

/**
 * 本次输出的原因。运行时产出，不落库。
 *
 * <h2>只有三种，因为输出只有一个来源：档位变了</h2>
 * 原先七种描述的是「为什么触发」（每次命中 / 窗口关闭 / 阈值达标 / 提前 / 最终），
 * 那是把触发机制暴露给了下游。档位模型下触发原因只有一个 —— 当前档位与上次
 * 已宣告的档位不同 —— 因此剩下的三个值描述的是<b>变化方向</b>，那才是下游真正要分派的东西：
 * 升档要建单、降档要更新单、恢复要关单。
 *
 * <p>删除的五个值（{@code EACH_MATCH} / {@code WINDOW_CLOSE} / {@code COUNT_THRESHOLD} /
 * {@code VALUE_THRESHOLD} / {@code EARLY} / {@code FINAL}）在新模型下没有对应场景：
 * 停留在同一档不产出，因此不存在「每次命中」；窗口关闭若档位没变也不产出，
 * 因此不存在「窗口关闭」这一独立原因。
 */
public enum FireType {

    /**
     * 升档：跃迁到更严重的档位，含 {@code NORMAL → 任意档}。
     */
    LEVEL_RAISE,
    /**
     * 降档：跃迁到较轻的档位，但仍未回到正常。
     *
     * <p>与恢复分开而不是合成「档位变化」：下游对二者的动作不同 ——
     * 降档通常是更新已有工单的严重度，恢复是关闭它。
     */
    LEVEL_LOWER,
    /**
     * 恢复：{@code 任意档 → NORMAL}，即全部档位条件都不再满足。
     *
     * <p>输出脚本据此分支产出「已恢复」文案。<b>恢复输出与告警输出走同一个 Topic、
     * 同一份 header 结构</b>，靠 {@code fireType} 区分 —— 另开 Topic 会让下游为同一条规则
     * 维护两套消费。
     *
     * <p><b>设备停止上报时不会产生恢复</b>：判档由消息驱动（窗口规则则由窗口结算驱动，
     * 而空窗口不会结算），没有数据就没有判据。把「静默」当成「恢复」会在设备掉线时
     * 批量误报恢复 —— 设备是否离线由 engine 的租约机制回答，不是规则引擎该猜的。
     */
    RECOVERY,
    /**
     * {@code EVERY_MATCH} 模式下每条命中消息的输出；无 {@code fromLevelCode}。
     */
    MATCH
}
